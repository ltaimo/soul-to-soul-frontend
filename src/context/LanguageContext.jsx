const interpolate = (text, params = {}) =>
  Object.entries(params).reduce((acc, [key, value]) => acc.replaceAll(`{${key}}`, String(value)), text);

export const LanguageContext = createContext();

export const LanguageProvider = ({ children }) => {
  const [language, setLanguage] = useState(() => localStorage.getItem('soul_language') || 'en');

  useEffect(() => {
    localStorage.setItem('soul_language', language);
  }, [language]);

  const value = useMemo(() => {
    const dictionary = translations[language] || translations.en;
    return {
      language,
      setLanguage,
      t: dictionary,
      translate: (key, params) => interpolate(dictionary[key] || translations.en[key] || key, params),
    };
  }, [language]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
};
